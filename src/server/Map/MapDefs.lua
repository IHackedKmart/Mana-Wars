-- Every arena players can vote for. Each entry controls the island's size, terrain shape,
-- materials, decoration, ruin style, lighting and weather. Add a new table to add a map.

local MapDefs = {}

local M = Enum.Material

export type Style = {
	stone: Enum.Material,
	stoneColors: { Color3 },
	floor: Enum.Material,
	floorColor: Color3,
	shrine: Enum.Material,
	shrineColor: Color3,
	wood: Color3,
	accent: Color3,
	plaza: Enum.Material,
	plazaColor: Color3,
	dais: Enum.Material,
	daisColor: Color3,
}

export type MapDef = {
	id: string,
	name: string,
