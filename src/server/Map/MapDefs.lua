-- Every arena players can vote for. Each entry controls the island's size, terrain shape and features
-- (rivers, mesas, a volcano), materials, decoration, landmarks, the look of the cornucopia, lighting,
-- clouds and weather. Add a new table to add a map.

local MapDefs = {}

local M = Enum.Material

export type Style = {
	stone: Enum.Material,
	stoneColors: { Color3 },
	floor: Enum.Material,
	floorColor: Color3,
	shrine: Enum.Material,
	shrineColor: Color3,
	wood: Color3,
	accent: Color3,
	plaza: Enum.Material,
	plazaColor: Color3,
	plazaColor2: Color3, -- the inlaid rings and spokes of the cornucopia floor
	dais: Enum.Material,
	daisColor: Color3,
	banner: { Color3 }, -- banner / awning / tent cloth colours
	flair: string, -- the cornucopia's themed decoration (see Structures.cornucopia)
}

export type Decor = {
	kind: string, -- "tree" | "rock" | "bush"
	styles: { string },
	count: number,
	cluster: { number }?, -- {min, max}: place in little groups instead of one by one
	spread: number?, -- how far a cluster spreads (studs)
	nearWater: number?, -- only within this many studs of water / lava / ice
}

export type MapDef = {
	id: string,
	name: string,
	icon: string,
	description: string,
	radius: number,
	terrain: {
		base: number,
		hills: number,
		hillScale: number,
		detail: number,
		rough: number,
		mountains: number,
		liquidLevel: number,
		liquid: Enum.Material,
		peakHeight: number,
		cliffHeight: number,
		-- optional features
		river: { scale: number, width: number, depth: number, dry: boolean? }?,
		mesas: { scale: number, threshold: number, step: number, steps: number }?,
		volcano: { height: number, radius: number, crater: number }?,
	},
	materials: {
		surface: Enum.Material,
		alt: Enum.Material,
		alt2: Enum.Material,
		shore: Enum.Material,
		cliff: Enum.Material,
		peak: Enum.Material,
		under: Enum.Material,
		path: Enum.Material,
		riverbed: Enum.Material?, -- dry rivers
		wet: { material: Enum.Material, height: number }?, -- a band of this just above the waterline
		patches: { { material: Enum.Material, scale: number, threshold: number } }?,
		strata: { Enum.Material }?, -- striped cliffs, bottom to top
	},
	colors: { [Enum.Material]: Color3 },
	paths: { width: number, crossing: string }, -- crossing: "bridge" | "causeway" | "none"
	decor: { Decor },
	pois: { string },
	poiCount: number,
	outerChests: number,
	style: Style,
	lighting: { [string]: any },
	atmosphere: { [string]: any },
	post: {
		saturation: number,
		contrast: number,
		brightness: number,
		tint: Color3,
		bloom: number,
		sunRays: number,
	},
	clouds: { cover: number, density: number, color: Color3 }?,
	water: { color: Color3, transparency: number, reflectance: number?, waves: number? },
	sky: string?, -- extra sky dressing: "Aurora"
	weather: string?,
	hazard: string?,
}

