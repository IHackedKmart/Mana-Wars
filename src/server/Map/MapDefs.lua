MapDefs.ById = {} :: { [string]: MapDef }
for _, def in MapDefs.List do
	MapDefs.ById[def.id] = def
end

-- The plaza (and pedestal ring) are flattened to this height.
function MapDefs.plazaHeight(def: MapDef): number
	return def.terrain.base + 1
end

-- What the vote screen needs to know (plain data so it can go over a remote).
function MapDefs.summary(def: MapDef): { [string]: any }
	return {
		id = def.id,
		name = def.name,
		icon = def.icon,
		description = def.description,
		radius = def.radius,
	}
end

return MapDefs
