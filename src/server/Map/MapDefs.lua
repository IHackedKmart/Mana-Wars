local function colors(overrides: { [Enum.Material]: Color3 }?): { [Enum.Material]: Color3 }
	local out = table.clone(BASE_COLORS)
	for k, v in (overrides or {}) :: { [Enum.Material]: Color3 } do
		out[k] = v
	end
	return out
end

