	[M.Snow] = Color3.fromRGB(232, 238, 248),
	[M.Glacier] = Color3.fromRGB(150, 205, 240),
	[M.Slate] = Color3.fromRGB(88, 92, 98),
	[M.Basalt] = Color3.fromRGB(42, 40, 44),
	[M.CrackedLava] = Color3.fromRGB(255, 110, 30),
	[M.Sandstone] = Color3.fromRGB(196, 150, 104),
	[M.Mud] = Color3.fromRGB(70, 56, 44),
}

local function colors(overrides: { [Enum.Material]: Color3 }?): { [Enum.Material]: Color3 }
	local out = table.clone(BASE_COLORS)
	for k, v in (overrides or {}) :: { [Enum.Material]: Color3 } do
		out[k] = v
	end
	return out
end

