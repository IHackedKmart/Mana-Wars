		alt2: Enum.Material,
		shore: Enum.Material,
		cliff: Enum.Material,
		peak: Enum.Material,
		under: Enum.Material,
	},
	colors: { [Enum.Material]: Color3 },
	decor: { { kind: string, styles: { string }, count: number } },
	pois: { string },
	poiCount: number,
	outerChests: number,
	style: Style,
	lighting: { [string]: any },
	atmosphere: { [string]: any },
	water: { color: Color3, transparency: number },
	weather: string?,
	hazard: string?,
}

